@Composable
fun NuvioTheme(
    darkTheme: Boolean = true,
    appTheme: AppTheme = AppTheme.MATERIAL_YOU,
    amoled: Boolean = false,
    customThemeColors: CustomThemeColors = CustomThemeColors.Default,
    content: @Composable () -> Unit,
) {
    val palette = remember(appTheme, customThemeColors) {
        ThemeColors.getColorPalette(appTheme, customThemeColors)
    }

    val platformDynamic = if (appTheme == AppTheme.MATERIAL_YOU) {
        rememberPlatformDynamicColorScheme(isDark = darkTheme, amoled = amoled)
    } else null

    val colorScheme = if (platformDynamic != null) {
        platformDynamic
    } else {
        val seed = if (appTheme == AppTheme.WHITE || appTheme == AppTheme.MATERIAL_YOU) {
            Color(0xFF6750A4)
        } else {
            palette.secondary
        }
        remember(seed, darkTheme, amoled) {
            dynamicColorScheme(
                seedColor = seed,
                isDark = darkTheme,
                isAmoled = amoled,
                style = PaletteStyle.Expressive,
            )
        }
    }

    val tokens = defaultNuvioThemeTokens(palette, amoled = amoled, colorScheme = colorScheme)

    val density = LocalDensity.current
    CompositionLocalProvider(
        LocalDensity provides Density(
            density = density.density,
            fontScale = 1f,
        ),
        LocalNuvioThemeTokens provides tokens,
        LocalNuvioTypeScale provides NuvioTypeTokens,
        LocalRippleConfiguration provides NuvioRippleConfiguration,
        LocalAppTheme provides appTheme,
        LocalThemePalette provides palette,
    ) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = NuvioTypography,
            shapes = NuvioShapes,
        ) {
            SkeletonAnimationProvider(content = content)
        }
    }
}
